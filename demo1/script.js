function initLoadingScreen() {
  const canvas = document.getElementById("loadingCanvas");
  const ctx    = canvas.getContext("2d");
  let particles = [];
  let raf;

  function resize() {
    canvas.width  = window.innerWidth;
    canvas.height = window.innerHeight;
    buildParticles();
  }

  function buildParticles() {
    const count = window.innerWidth < 600 ? 80 : 140;
    particles = Array.from({ length: count }, () => ({
      x:     Math.random() * canvas.width,
      y:     Math.random() * canvas.height,
      r:     Math.random() * 1.4 + 0.3,
      alpha: Math.random() * 0.55 + 0.15,
      vy:    Math.random() * 0.35 + 0.06,
      twink: Math.random() * Math.PI * 2,
      ts:    Math.random() * 0.02 + 0.005,
      type:  Math.random() > 0.82 ? "heart" : "star"
    }));
  }

  resize();
  window.addEventListener("resize", resize, { passive: true });

  function drawMiniHeart(x, y, size, alpha) {
    ctx.save();
    ctx.globalAlpha = alpha;
    ctx.fillStyle = "#ff4f9a";
    ctx.translate(x, y);
    ctx.scale(size, size);
    ctx.beginPath();
    ctx.moveTo(0, -2);
    ctx.bezierCurveTo(0, -5, -4, -5, -4, -1.5);
    ctx.bezierCurveTo(-4, 1, 0, 4.5, 0, 6);
    ctx.bezierCurveTo(0, 4.5, 4, 1, 4, -1.5);
    ctx.bezierCurveTo(4, -5, 0, -5, 0, -2);
    ctx.fill();
    ctx.restore();
  }

  function animate() {
    raf = requestAnimationFrame(animate);
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    particles.forEach(p => {
      p.y -= p.vy;
      p.twink += p.ts;
      if (p.y < -12) { p.y = canvas.height + 12; p.x = Math.random() * canvas.width; }
      const a = p.alpha * (0.55 + 0.45 * Math.sin(p.twink));
      if (p.type === "heart") {
        drawMiniHeart(p.x, p.y, p.r * 0.9, a * 0.45);
      } else {
        ctx.beginPath();
        ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
        ctx.fillStyle = `rgba(255,248,252,${a})`;
        ctx.fill();
      }
    });
  }
  animate();

  // Reveal text lines sequentially
  ["ll1","ll2","ll3"].forEach((id, i) => {
    setTimeout(() => {
      const el = document.getElementById(id);
      if (el) el.classList.add("visible");
    }, 700 + i * 750);
  });

  // Show enter button
  setTimeout(() => {
    const btn = document.getElementById("enterBtn");
    if (btn) btn.classList.add("visible");
  }, 700 + 3 * 750 + 400);

  // Enter button
  document.getElementById("enterBtn").addEventListener("click", enterSite);
}

