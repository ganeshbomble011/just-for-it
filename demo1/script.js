/* ============================================================
   CELEBRATION CANVAS — hearts & confetti burst
============================================================ */
function startCelebrationCanvas() {
  const canvas = document.getElementById("celebCanvas");
  if (!canvas) return;
  const ctx = canvas.getContext("2d");
  canvas.width  = window.innerWidth;
  canvas.height = window.innerHeight;

  const COLORS  = ["#ff4f9a","#ffb6d5","#f6c667","#9b59b6","#e63967","#fff8fc","#ff85b3"];
  const isMobile = window.innerWidth < 768;
  const total   = isMobile ? 130 : 250;

  const particles = Array.from({ length: total }, () => ({
    x:        Math.random() * canvas.width,
    y:        Math.random() * canvas.height * 0.5 - canvas.height * 0.3,
    vx:       (Math.random() - 0.5) * 4,
    vy:       Math.random() * 4 + 1,
    r:        Math.random() * 10 + 4,
    color:    COLORS[Math.floor(Math.random() * COLORS.length)],
    type:     Math.random() > 0.38 ? "heart" : "circle",
    rot:      Math.random() * Math.PI * 2,
    rotV:     (Math.random() - 0.5) * 0.1,
    alpha:    Math.random() * 0.5 + 0.5,
    decay:    Math.random() * 0.003 + 0.001
  }));

  function drawHeart(x, y, size) {
    ctx.save();
    ctx.translate(x, y);
    ctx.scale(size / 10, size / 10);
    ctx.beginPath();
    ctx.moveTo(0, -3);
    ctx.bezierCurveTo(0, -6, -5, -6, -5, -2);
    ctx.bezierCurveTo(-5, 2, 0, 6, 0, 8);
    ctx.bezierCurveTo(0, 6, 5, 2, 5, -2);
    ctx.bezierCurveTo(5, -6, 0, -6, 0, -3);
    ctx.fill();
    ctx.restore();
  }

  let frame = 0;
  const MAX_FRAMES = 700;

  function loop() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    particles.forEach(p => {
      p.x     += p.vx;
      p.y     += p.vy;
      p.vy    += 0.05;
      p.rot   += p.rotV;
      p.alpha -= p.decay;

      if (p.y > canvas.height + 20) {
        // Recycle particle from top for continuous rain
        p.y     = -20;
        p.x     = Math.random() * canvas.width;
        p.alpha = Math.random() * 0.5 + 0.5;
        p.vy    = Math.random() * 3 + 1;
      }

      if (p.alpha <= 0) return;
      ctx.save();
      ctx.globalAlpha = p.alpha;
      ctx.fillStyle   = p.color;
      ctx.translate(p.x, p.y);
      ctx.rotate(p.rot);
      if (p.type === "heart") drawHeart(0, 0, p.r);
      else { ctx.beginPath(); ctx.arc(0, 0, p.r / 2, 0, Math.PI * 2); ctx.fill(); }
      ctx.restore();
    });

    if (++frame < MAX_FRAMES) requestAnimationFrame(loop);
    else ctx.clearRect(0, 0, canvas.width, canvas.height);
  }
  loop();
}

