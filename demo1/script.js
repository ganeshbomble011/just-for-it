let _twTimer = null;

function startTypewriter(el, text, speed, onDone) {
  el.innerHTML = "";
  let i = 0;
  const caret = Object.assign(document.createElement("span"), { className: "cursor-blink" });
  el.appendChild(caret);
  _twTimer = setInterval(() => {
    if (i < text.length) {
      caret.insertAdjacentText("beforebegin", text[i++]);
    } else {
      clearInterval(_twTimer);
      _twTimer = null;
      caret.remove();
      if (onDone) onDone();
    }
  }, speed);
}

function stopTypewriter() {
  if (_twTimer) { clearInterval(_twTimer); _twTimer = null; }
}

